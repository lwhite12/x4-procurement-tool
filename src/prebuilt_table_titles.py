def localize_prebuilt_tables(tables: list[dict], share_key: str, lang: str) -> list[dict]:
    """Returns a copy of `tables` (a component_analyzer_tables share
    payload -- always a list, see buildComponentAnalyzerTablesPayload() in
    app.js) with each table's own `title` and every `statSets[].name`
    swapped to their `lang` translation, wherever both `share_key` and
    that exact English title/tab text are known (see module docstring).
    Anything not recognized is left exactly as it was, so this is always
    safe to call even on a real user's own shared table.
    """
    translated_title = TABLE_TITLES.get(share_key, {}).get(lang)
    result = []
    for table in tables:
        new_table = dict(table)
        if translated_title:
            new_table["title"] = translated_title
        stat_sets = table.get("statSets")
        if isinstance(stat_sets, list):
            new_stat_sets = []
            for stat_set in stat_sets:
                new_name = TAB_TITLES.get(stat_set.get("name"), {}).get(lang)
                new_stat_sets.append({**stat_set, "name": new_name} if new_name else stat_set)
            new_table["statSets"] = new_stat_sets
        result.append(new_table)
    return result
